import { test, expect } from '@playwright/test';

test('проект выбирается из своих записей, создаётся и убирается плашкой, выбор сохраняется', async ({ page, request }) => {
  await request.post('/api/reset', { data: { confirmation: 'СБРОСИТЬ КИЗУНА' } });
  const create = async (raw) => (await (await request.post('/api/captures', { data: { raw, primaryType: 'todo' } })).json()).entry;
  const source = await create('Проверить проект');
  await request.post(`/api/captures/${source.id}/corrections`, { data: { patch: { project: 'Zadolbator' } } });
  const entry = await create('Выбрать проект задачи');
  const open = async () => {
    await page.goto(`/#today?open=${entry.id}`);
    await expect(page.locator('#review-dialog')).toBeVisible();
    if (await page.locator('#review-params-toggle').getAttribute('aria-expanded') === 'false') await page.locator('#review-params-toggle').click();
  };
  const input = page.getByRole('combobox', { name: 'Проект', exact: true });
  const selected = page.locator('.project-selected-name');
  const saved = async () => (await (await request.get(`/api/captures/${entry.id}`)).json()).entry.interpretation.classification.entities.projects;
  await open();
  await input.click();
  await expect(page.getByRole('option', { name: 'Zadolbator', exact: true })).toBeVisible();
  await input.fill('Zad');
  await page.getByRole('option', { name: 'Zadolbator', exact: true }).click();
  await expect(selected).toHaveText('Zadolbator');
  await expect(input).toBeHidden();
  await page.locator('#review-close').click();
  await expect.poll(saved).toEqual(['Zadolbator']);
  await open();
  await expect(selected).toHaveText('Zadolbator');
  await selected.click();
  await input.fill('Новый проект');
  await expect(page.getByRole('option', { name: 'Создать проект «Новый проект»' })).toBeVisible();
  await input.press('ArrowDown');
  await input.press('Enter');
  await expect(selected).toHaveText('Новый проект');
  await page.locator('#review-close').click();
  await expect.poll(saved).toEqual(['Новый проект']);
  await page.setViewportSize({ width: 390, height: 900 });
  await open();
  await page.getByRole('button', { name: 'Убрать проект' }).click();
  await expect(input).toBeVisible();
  await input.fill('Zad');
  await input.press('Escape');
  await expect(page.locator('#review-params-toggle')).toHaveAttribute('aria-expanded', 'true');
  await input.click();
  await input.fill('Zad');
  await input.press('ArrowDown');
  await input.press('Enter');
  await expect(selected).toHaveText('Zadolbator');
  const box = await selected.boundingBox();
  expect(box.x + box.width).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Убрать проект' }).click();
  await page.locator('#review-close').click();
  await expect.poll(saved).toEqual([]);
});
